    // ══════════════════════════════════════════════════════════════════════════
    // 5. MULTI-ROUND CONSISTENCY
    //
    // Verify that over a full N-round lifecycle:
    //   - Each member receives the pot exactly once
    //   - Reputation is incremented exactly once per member per payout
    //   - The circle reaches Completed after N rounds
    //   - No residual token balance (beyond collateral) remains
    // ══════════════════════════════════════════════════════════════════════════

    #[test]
    fn test_payout_each_member_receives_pot_exactly_once() {
        let t = fixture();
        t.join_all();

        let member_count = t.member_count();
        let pot = ROUND_AMOUNT * member_count as i128;

        // Record pre-payout balances (after joining and contributing nothing yet)
        // We use the balances after all joins since collateral is already deducted.
        let balances_after_join: std::vec::Vec<i128> = (0..member_count)
            .map(|i| t.token.balance(&t.member(i)))
            .collect();

        // Run all rounds
        for _ in 0..member_count {
            t.contribute_all();
            t.circle.payout();
        }

        // Each member:
        //   - contributed ROUND_AMOUNT × member_count times (once per round)
        //   - received pot (ROUND_AMOUNT × member_count) exactly once
        // Net change per member = pot - (ROUND_AMOUNT × member_count) = 0
        // So post-payout balance == balance-after-join (contributions cancel out)
        for i in 0..member_count {
            let m = t.member(i);
            let net = t.token.balance(&m) - balances_after_join[i as usize];
            assert_eq!(
                net, 0,
                "member {} net balance change must be 0 (received pot once, contributed N times)",
                i,
            );
        }
    }

    #[test]
