//! Payout cross-contract integration tests.
//!
//! These tests exercise the `payout` entry-point at the boundary between the
//! circle contract, the USDC token contract, and the reputation contract.
//! Every test uses real Soroban test-environment contracts (no hand-rolled
//! mocks) with injected failure states so the rollback semantics are
//! exercised by the same execution engine that production code runs on.
//!
//! # What is tested
//!
//! | Group | Focus |
//! |---|---|
//! | Success path | Full payout: balances, reputation, round advancement, events |
//! | Token failure | Underfunded circle rolls back paid_out, RoundsCompleted, reputation |
//! | Reputation failure | Unregistered circle rolls back token transfer and paid_out |
//! | Atomicity invariants | Every failure mode leaves a consistent, retryable state |
//! | Multi-round consistency | Payout increments reputation exactly once per round |
//! | Event emission | payout + completed events carry correct payloads |
//!
//! # Design constraints
//!
//! - No real wallets, no live RPC — all execution is in `Env::default()`.
//! - All addresses are generated by the Soroban test harness.
//! - `mock_all_auths()` is called once per fixture so auth is not the focus.
//! - Failure states are injected by draining the circle's token balance or by
//!   withholding reputation registration — the same patterns used in
//!   `transfer_failure_tests.rs` and `lifecycle_invariant_tests.rs`.

