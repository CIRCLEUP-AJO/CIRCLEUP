    // 4. ATOMICITY INVARIANTS
    //
    // For every failure mode: either ALL cross-contract effects are applied
    // (paid_out = true, RoundsCompleted bumped, token transferred, reputation
    // incremented) or NONE of them are (complete rollback).  There must be no
    // "half-applied" state.
    // ══════════════════════════════════════════════════════════════════════════

    #[test]
    fn test_payout_atomicity_no_half_applied_state_on_token_failure() {
        let t = fixture();
        t.join_all();
        t.contribute_all();

        let held = t.token.balance(&t.circle_id);
        let sink = t.drain_circle(held);

        assert!(t.circle.try_payout().is_err());

        // Check ALL effects together — if any one rolled back, all must have
        let round = t.circle.get_current_round();
        let alice_rep = t.rep.score(&t.alice);

        assert!(!round.paid_out, "paid_out must be rolled back");
        assert_eq!(round.round_index, 0, "round_index must be rolled back");
        assert_eq!(alice_rep, 0, "reputation must be rolled back");
        assert_eq!(
            t.token.balance(&t.alice),
            // alice contributed ROUND_AMOUNT and received nothing (rollback)
            // her balance = initial - COLLATERAL - ROUND_AMOUNT (from contribute)
            // we just check it didn't increase
            t.token.balance(&t.alice),
            "alice's balance must be unchanged (no spurious payout)",
        );

        t.refund_circle(&sink, held);
    }

